CREATE TABLE usuarios (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL,
    senha VARCHAR(100) NOT NULL,
    role  VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_role CHECK (role IN ('ADMIN', 'VENDEDOR'))
);

CREATE TABLE clientes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    email     VARCHAR(160) NOT NULL,
    cpf       VARCHAR(11)  NOT NULL,
    telefone  VARCHAR(20),
    criado_em TIMESTAMP    NOT NULL,
    CONSTRAINT uk_clientes_email UNIQUE (email),
    CONSTRAINT uk_clientes_cpf UNIQUE (cpf)
);

CREATE TABLE produtos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(120)   NOT NULL,
    descricao          VARCHAR(500),
    preco              NUMERIC(12, 2) NOT NULL,
    quantidade_estoque INTEGER        NOT NULL,
    ativo              BOOLEAN        NOT NULL,
    versao             BIGINT         NOT NULL,
    CONSTRAINT ck_produtos_preco CHECK (preco > 0),
    CONSTRAINT ck_produtos_estoque CHECK (quantidade_estoque >= 0)
);

CREATE TABLE pedidos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT         NOT NULL,
    status      VARCHAR(30)    NOT NULL,
    valor_total NUMERIC(14, 2) NOT NULL,
    criado_em   TIMESTAMP      NOT NULL,
    pago_em     TIMESTAMP,
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT ck_pedidos_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'CANCELADO'))
);

CREATE TABLE itens_pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT         NOT NULL,
    produto_id     BIGINT         NOT NULL,
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_itens_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_itens_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT ck_itens_quantidade CHECK (quantidade > 0)
);

CREATE TABLE movimentacoes_estoque (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT       NOT NULL,
    tipo       VARCHAR(10)  NOT NULL,
    quantidade INTEGER      NOT NULL,
    motivo     VARCHAR(200) NOT NULL,
    criado_em  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_movimentacoes_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT ck_movimentacoes_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT ck_movimentacoes_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_pedidos_cliente ON pedidos (cliente_id);
CREATE INDEX idx_pedidos_status_pago_em ON pedidos (status, pago_em);
CREATE INDEX idx_itens_pedido ON itens_pedido (pedido_id);
CREATE INDEX idx_itens_produto ON itens_pedido (produto_id);
CREATE INDEX idx_movimentacoes_produto ON movimentacoes_estoque (produto_id, criado_em);
